"""Write the synthetic Demo Studio data as upload-ready folders, WITHOUT importing or training anything.

Use it to set a team up from zero through the app (Team setup -> Upload images), exactly as a real team would.

    .venv/Scripts/python scripts/export_synthetic_dataset.py [out_dir]

Default out_dir: synthetic_dataset/ next to this repo's backend (git-ignored). Same seed as make_demo_team.py, so the
images match the demo team. Layout:

    1_team_posts/        90 posts in the house style + meta.csv (posted_at, likes, caption)   -> "Our team's posts"
    2_other_pages/       60 posts from other clubs                                             -> "Other pages' posts"
    3_accepted_designs/  versions the simulated seniors accepted + meta.csv (project per file)  -> "Designs the seniors accepted"
    4_rejected_designs/  versions they rejected + meta.csv (project per file)                  -> "Rejected drafts"
    5_test_kit/          3 NEW briefs (3 versions each) for live checks; ANSWERS.md says what the seniors decided
    README.md            step-by-step
"""
from __future__ import annotations

import csv
import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import make_demo_team as M  # noqa: E402

RULE_WORDS = {"off_palette": "colours outside the palette", "wrong_font": "wrong typeface", "centered": "centred layout",
              "small_title": "title too small", "clutter": "cluttered with small elements", "low_contrast": "low contrast",
              "no_accent": "missing the accent shape", "busy_bg": "busy background", "cramped": "cramped spacing"}


def write_csv(path: Path, header: list[str], rows: list[list]):
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def main(out: Path):
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    with tempfile.TemporaryDirectory() as tmp:
        hist, other, briefs_dir, briefs, kit = M.build(Path(tmp))
        team_dir, other_dir = out / "1_team_posts", out / "2_other_pages"
        acc_dir, rej_dir, kit_dir = out / "3_accepted_designs", out / "4_rejected_designs", out / "5_test_kit"
        for d in (team_dir, other_dir, acc_dir, rej_dir, kit_dir):
            d.mkdir()

        meta = list(csv.DictReader((hist / "meta.csv").open(encoding="utf-8")))
        for r in meta:
            shutil.copy2(hist / r["filename"], team_dir / r["filename"])
        write_csv(team_dir / "meta.csv", ["filename", "posted_at", "likes", "caption"],
                  [[r["filename"], r["posted_at"], r["likes"], r["caption"]] for r in meta])

        for f in sorted(other.glob("*.png")):
            shutil.copy2(f, other_dir / f.name)

        acc, rej = [], []
        for b in briefs:
            for j, v in enumerate(b["versions"]):
                name = f"{b['project']}_v{j + 1}.png"            # the file name does not reveal the decision
                dest = acc_dir if v["decision"] == "accepted" else rej_dir
                shutil.copy2(briefs_dir / v["file"], dest / name)
                (acc if v["decision"] == "accepted" else rej).append([name, b["project"]])
        write_csv(acc_dir / "meta.csv", ["filename", "project"], acc)
        write_csv(rej_dir / "meta.csv", ["filename", "project"], rej)

        answers = json.loads((kit / "ANSWERS.json").read_text())
        for a in answers:
            shutil.copy2(kit / a["file"], kit_dir / a["file"])
        lines = ["# Test kit: what the simulated seniors decided", "",
                 "Three new briefs the model never sees during setup. Check each version with **Check my design**",
                 "(use the brief name as the project), then compare the scores with the decisions below.", "",
                 "These decisions follow the seniors' rules exactly (no random flips). The training data is noisier on",
                 "purpose: there, about 1 decision in 10 is flipped to imitate inconsistent people.", "",
                 "Objection is how strongly the seniors dislike a version (sum of the rule weights it breaks, plus a",
                 "little noise; below about 0.6 is fine). Within a brief the version with the lowest objection is accepted.", "",
                 "| File | Seniors | Objection | What is wrong with it |", "|---|---|---|---|"]
        lines += [f"| {a['file']} | {a['seniors']} | {a.get('penalty', '')} | "
                  f"{', '.join(RULE_WORDS.get(x, x) for x in a['breaks']) or 'nothing'} |" for a in answers]
        (kit_dir / "ANSWERS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    n_acc, n_rej = len(acc), len(rej)
    readme = f"""# Synthetic test data for VibeCheck (Demo Studio)

Everything here is **invented**: posters generated by `scripts/make_demo_team.py` (seed 7) for a design team that does
not exist, with simulated likes and simulated seniors. Present it as synthetic.

| Folder | Upload as | What it is |
|---|---|---|
| `1_team_posts/` | Our team's posts (approved) | 90 posts in the house style, Mar to Nov 2026, with dates and likes in meta.csv |
| `2_other_pages/` | Other pages' posts (not our vibe) | 60 posts from other clubs in other styles |
| `3_accepted_designs/` | Designs the seniors accepted | {n_acc} versions that were accepted; meta.csv gives each one's project |
| `4_rejected_designs/` | Rejected drafts | {n_rej} versions that were rejected; meta.csv gives each one's project |
| `5_test_kit/` | do not upload | 3 new briefs to check live; ANSWERS.md has the seniors' decisions |

The house style: navy or off-white background, coral and teal accents, a heavy left-aligned title, one big accent
circle or stripe, lots of empty space. The simulated seniors reject (most to least strongly): colours outside the
palette, a small title, low contrast, clutter, the wrong typeface, a busy background, cramped spacing, a centred layout,
a missing accent shape. Each decision has some noise and 10% of them are flipped, like real people.

## Set the team up from zero

1. Start VibeCheck with an empty data folder, e.g. `VIBE_DATA_DIR=data_test`, and open it.
2. **Add a design team**: name it e.g. "Demo Studio (synthetic)". Leave the Instagram fields empty.
3. **Team setup -> Upload images**, four times. In each, choose what the images are, then select **all files in the
   folder, including meta.csv**. Untick "Retrain after this upload" for the first three:
   1. `1_team_posts` as *Our team's posts*
   2. `2_other_pages` as *Other pages' posts*
   3. `3_accepted_designs` as *Designs the seniors accepted* (leave Project empty: meta.csv sets it per image)
   4. `4_rejected_designs` as *Rejected drafts*, with "Retrain after this upload" **ticked**
4. Wait for the training job under *Imports and training* (several minutes on a laptop CPU: it computes CLIP features,
   text detection and the approval model).
5. **Team style** shows what it learned; the approval model should switch itself on (it needs at least 8 accepted,
   8 rejected and 3 projects).
6. Check the `5_test_kit` posters with **Check my design** and compare with `ANSWERS.md`. Mark the seniors' decision on
   each result to see the adaptive loop.
"""
    (out / "README.md").write_text(readme, encoding="utf-8")
    print(f"wrote {out}: 90 team posts, 60 other-page posts, {n_acc} accepted, {n_rej} rejected, {len(answers)} test-kit posters")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "synthetic_dataset")
